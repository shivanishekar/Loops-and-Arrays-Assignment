// 1. Write a program to create String array and print all the values in that array.
public class StringArrayExample {

    public static void main(String[] args) {

        String[] names = {"Ram", "Sita", "Lakshman", "Hanuman"};

        for (int i = 0; i < names.length; i++) {
            System.out.println(names[i]);
        }
    }
}
/* output : 
Ram
Sita
Lakshman
Hanuman */
